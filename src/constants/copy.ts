export type AppCopy = typeof en;

/**
 * Structural translation shape: identical keys to English, but with every
 * literal widened to `string`. Every language table in `src/localization/`
 * must satisfy this type, so the compiler rejects missing or extra keys while
 * leaving wording free. Arrays keep their exact length, so lists like the
 * onboarding slides stay structurally parallel across languages.
 */
type WidenTree<T> =
    T extends (...args: infer A) => infer R
        ? (...args: A) => WidenTree<R>
        : T extends string
            ? string
            : T extends number
                ? number
                : T extends object
                    ? { [K in keyof T]: WidenTree<T[K]> }
                    : T;

export type Translation = WidenTree<typeof en>;

/**
 * Languages the app knows. Each new code needs a registry entry in
 * `src/localization/languages.ts`; a table under `src/localization/<code>.ts`
 * is what makes it selectable instead of falling back to English.
 */
export type Language = "en" | "hi" | "fr" | "es" | "zh" | "ja" | "ko" | "ar" | "ur";

/**
 * Swap the active copy table at runtime. `copy` is a deliberate module-level
 * singleton: every one of the 90+ `copy.*` call sites keeps working unchanged
 * while the active language switches. UI re-renders through
 * `LanguageProvider`, which re-renders its subtree when the language changes.
 */
export function applyLanguage(table: Translation): void {
    Object.assign(copy, table);
}

/**
 * Deep copy that keeps interpolation functions by reference. `copy` must be
 * independent of `en`: applying a language writes into `copy`'s own tree, and
 * if `copy` aliased `en`, the English source of truth would be corrupted by
 * the first switch and could never be restored.
 */
function cloneTable<T>(value: T): T {
    if (typeof value === "function") return value;
    if (Array.isArray(value)) return value.map(cloneTable) as unknown as T;
    if (value && typeof value === "object") {
        const out: Record<string, unknown> = {};
        for (const [key, item] of Object.entries(value)) out[key] = cloneTable(item);
        return out as T;
    }
    return value;
}

export const copy: AppCopy = cloneTable(en);

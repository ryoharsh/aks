/**
 * Centralized user-visible copy — English source of truth.
 *
 * Every static string the user can read (screen text, buttons, placeholders,
 * accessibility labels, dialogs, notices, and error lines shown in the UI)
 * lives here. Screens and components must reference `copy` instead of
 * hardcoding literals, so nothing user-facing is scattered across the app.
 *
 * Rules:
 * - English is the canonical structure; translations live in
 *   `src/localization/<code>.ts` and must satisfy `Translation`.
 * - Dynamic values use functions, e.g. `connectedSources(3)`.
 * - URLs, email addresses, asset paths, and formatting helpers
 *   (Intl formatters, `replaceAll("_", " ")`) stay at the call site —
 *   they are data/formatting, not translatable copy.
 * - Logic-coupled identifiers (route names, filter keys shared with
 *   grouping logic, status codes) stay where they are.
 *
 * Runtime: `copy` is mutable through `applyLanguage` (used by
 * `LanguageProvider`), so the 90+ `copy.*` call sites keep working unchanged
 * while the active language switches. Language registration lives in
 * `src/localization/languages.ts`.
 */

